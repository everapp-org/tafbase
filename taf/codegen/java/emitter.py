def emit(m, outdir):
    """Write a complete Maven + JUnit 5 + Playwright-Java 21++ project into outdir."""
    art = spec.artifacts()
    files = {
        "pom.xml": _pom(m),
        f"{_PKG_DIR}/package-info.java": _package_info(),
        f"{_PKG_DIR}/BaseTest.java": _basetest(m),
        f"{_PKG_DIR}/TafJournal.java": _journal_class(),
        f"{_PKG_DIR}/SoftChecks.java": _softchecks_class(),
        f"{_PKG_DIR}/JourneysTest.java": _journeys_class(m),
        "taf.manifest.json": json.dumps(ops.manifest(m), indent=2, sort_keys=True) + "\n",
    }
    for name, st in m["states"].items():
        files[f"{_PKG_DIR}/{_state_class(name)}.java"] = _page_class(name, st)
    el = _elements_class(m)
    if el is not None:
        files[f"{_PKG_DIR}/Elements.java"] = el
    act = _actions_class(m)
    if act is not None:
        files[f"{_PKG_DIR}/Actions.java"] = act

    for k in list(files):
        for aname, fname in art.items():
            files[k] = files[k].replace("@@%s@@" % aname, fname)
    written = []
    for rel, text in sorted(files.items()):
        p = os.path.join(outdir, rel)
        os.makedirs(os.path.dirname(p), exist_ok=True)
        with open(p, "w", encoding="utf-8") as f:
            f.write(text)
        written.append(p)
    readme = os.path.join(outdir, "custom", "README.md")
    if not os.path.exists(readme):
        os.makedirs(os.path.dirname(readme), exist_ok=True)
        with open(readme, "w", encoding="utf-8") as f:
            f.write(_CUSTOM_README)
    return written
