def _write(outdir, files):
    written = []
    for name, content in files.items():
        if content is None:
            continue
        for k, v in _s.artifacts().items():
            content = content.replace("@@%s@@" % k, v)
        path = os.path.join(outdir, name)
        parent = os.path.dirname(path)
        if parent:
            os.makedirs(parent, exist_ok=True)
        with open(path, "w", encoding="utf-8") as f:
            f.write(content)
        written.append(path)
    return written


def emit_framework(outdir):
    """Vendor command — no model. The SUT-agnostic taf-runtime project."""
    return _write(outdir, framework_files())


def emit_tests(m, outdir, framework="../taf-runtime"):
    """User command — the SUT-bound suite, compiling the framework at
    `framework` via ${taf.framework.src}."""
    files = {"pom.xml": _POM.format(
                artifact_id=m["sut"]["name"],
                framework_src=os.path.join(framework, "src", "main", "java")),
             os.path.join("src", "test", "resources", "META-INF", "services",
                          "taf.runtime.SutProfile"): _services_entry(m)}
    pkg = os.path.join("src", "test", "java") + "/" + _PKG.replace(".", "/")
    files[os.path.join(pkg, "package-info.java")] = _PACKAGE_INFO
    files[os.path.join(pkg, "SutConfig.java")] = _sut_config(m)
    for name, st in m["states"].items():
        files[os.path.join(pkg, "%s.java" % ops.state_class(name))] = \
            _page_class(name, st)
    files[os.path.join(pkg, "Elements.java")] = _elements_class(m)
    files[os.path.join(pkg, "Actions.java")] = _actions_class(m)
    for jtype, cls in _SUITE_FILES.items():
        files[os.path.join(pkg, "%s.java" % cls)] = _suite_file(m, jtype)
    files["taf.manifest.json"] = _manifest(m)
    files["taf.suite.json"] = _suite_json(m, framework)
    files[os.path.join("custom", "README.md")] = _CUSTOM_README
    return _write(outdir, files)


def emit(model, outdir):
    """The compat single dir — suite at the root, framework nested.
    `taf emit` keeps working; emit-framework + emit-tests is the
    separated form."""
    written = emit_tests(model, outdir, framework="./taf-runtime")
    written += emit_framework(os.path.join(outdir, "taf-runtime"))
    return written


def _manifest(m):
    return json.dumps(ops.manifest(m), indent=2, sort_keys=True) + "\n"


def _suite_json(m, framework):
    from taf import model as _model
    return json.dumps(
        ops.suite_info(m, "java", framework, _model.env_needs(m)),
        indent=2, sort_keys=True) + "\n"
