"""Shared machinery for the Java codegen — spec access,
name transforms, template substitution, the locator ladder."""

import json
import os

from taf import ops

_PKG = "taf.generated"
_PKG_DIR = "src/test/java/" + _PKG.replace(".", "/")


_DSL = {}


_HEADER = "// Generated by tafbase (taf emit --lang java). Do not edit —\n" \
          "// edit the model and regenerate.\n"


def _j(name):
    return ops.camel(name)


def _state_class(name):
    return ops.state_class(name)


def _spec():
    if "spec" not in _DSL:
        from taf import dsl_parse
        path = os.path.join(os.path.dirname(__file__), "..", "..", "..",
                            "dsl", "framework-spec.dsl")
        _DSL["spec"] = dsl_parse.parse(open(path).read())
    return _DSL["spec"]


def _rungs():
    return _spec()["locators"]


def _forms():
    return _spec()["vocabulary"]


def _esc(v):
    return str(v).replace("\\", "\\\\").replace('"', '\\"')


def _sub(t, kw):
    for k, v in kw.items():
        t = t.replace("${%s}" % k, str(v))
    return t


def _variant_entry(entry, keys):
    if "variants" not in entry:
        return entry
    ks = sorted(keys)
    for v in entry["variants"]:
        if sorted(v["when"]) == ks:
            return v
    return entry


def _sp(entry, **kw):
    """One spelled line from a table entry."""
    return _sub(entry["spell"]["java"], kw)


def _loc(loc):
    """The Playwright-Java locator call for one rung of the ladder —
    spelled by dsl/locators.dsl.json."""
    rung, l = ops.locator_rung(loc)
    entry = _rungs()[rung]
    v = _variant_entry(entry, [k for k in loc if k != entry["key"]])
    kw = {k: _esc(l[k]) for k in l}
    kw["role_enum"] = l.get("role", "").upper()
    return _sp(v, page="page", **kw)


def _jsonpath(p):
    """'$.a.b' -> .get("a").get("b") — v1 supports dotted keys only."""
    return "".join(f'.get("{k}")' for k in str(p).lstrip("$").split(".") if k)

