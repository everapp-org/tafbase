"""Shared machinery for the TypeScript codegen — spec access,
the locator ladder spelled, name transforms, small helpers."""

import json
import os

from taf import ops


_HEADER = "// Generated by tafbase (taf emit --lang ts). Do not edit —\n" \
          "// edit the model and regenerate.\n"

_DSL = {}
_LANG = "ts"


def _spec():
    if "spec" not in _DSL:
        from taf import spec as _s
        _DSL["spec"] = _s.spec()
    return _DSL["spec"]


def _rungs():
    return _spec()["locators"]


def _forms():
    return _spec()["vocabulary"]


def _esc(v):
    """A value spliced into a spelled template — escaped the way the
    target language escapes inside a double-quoted literal."""
    return json.dumps(str(v))[1:-1]


def _sub(t, kw):
    for k, v in kw.items():
        t = t.replace("${%s}" % k, str(v))
    return t


def _variant_entry(entry, keys):
    if "variants" not in entry:
        return entry
    ks = sorted(keys)
    for v in entry["variants"]:
        if sorted(v["when"]) == ks:
            return v
    return entry


def _sp(entry, **kw):
    """One spelled line from a spec entry."""
    val = entry["spell"][_LANG]
    if isinstance(val, list):
        return [_sub(line, kw) for line in val]
    return _sub(val, kw)


def _loc(loc, page="page"):
    """The Playwright call for one rung of the locator ladder —
    spelled by taf/dsl/framework-spec.dsl."""
    rung, l = ops.locator_rung(loc)
    entry = _rungs()[rung]
    v = _variant_entry(entry, [k for k in loc if k != entry["key"]])
    kw = {k: _esc(l[k]) for k in l}
    return _sp(v, page=page, **kw)


def _jsonpath(p):
    """'$.a.b' -> '["a"]["b"]'. v1 supports dotted keys only."""
    return "".join(f'[{json.dumps(k)}]' for k in str(p).lstrip("$").split(".") if k)


def _state_class(name):
    return ops.state_class(name)


__all__ = ["json", "os", "ops", "_DSL", "_LANG", "_HEADER", "_spec",
           "_rungs", "_forms", "_esc", "_sub", "_variant_entry", "_sp",
           "_loc", "_jsonpath", "_state_class"]
